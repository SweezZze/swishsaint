    func failSecureInput(app: String?) -> String {
        app.map { String(format: failSecureInputFormat, $0) } ?? failSecureInput
    }

    func triggerName(_ trigger: ForkDictationTrigger) -> String {
        switch trigger {
        case .rightCommand: return triggerRightCommand
        case .rightOption: return triggerRightOption
        case .rightControl: return triggerRightControl
        case .rightShift: return triggerRightShift
        case .leftCommand: return triggerLeftCommand
        case .leftOption: return triggerLeftOption
        case .leftControl: return triggerLeftControl
        case .leftShift: return triggerLeftShift
        case .fn: return triggerFn
        }
    }

    static func strings(_ language: AppLanguage) -> ForkDictationStrings {
        switch language {
        case .enUS: return .enUS
        case .ptBR: return .ptBR
        case .tr: return .tr
        case .ru: return .ru
        case .es: return .es
        case .sk: return .sk
        case .de: return .de
        case .fr: return .fr
