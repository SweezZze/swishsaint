    let qualityLight: String
    let qualityStandard: String
    let qualityHigh: String
    let qualityLightCaption: String
    let qualityStandardCaption: String
    let qualityHighCaption: String
    /// The size per hour beside a quality; %@ is a decimal number.
    let perHourFormat: String
    let libraryTitle: String
    let folderTitle: String
    let folderChange: String
    let folderOpen: String
    let folderPanelMessage: String
    let folderPanelPrompt: String
