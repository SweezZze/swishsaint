    /// The status shown where the other rows say granted or missing.
    let systemAudioUnknown: String
    let systemAudioCaption: String
    let systemAudioCheck: String
    let shortcutTitle: String
    let shortcutLabel: String
    let shortcutNone: String
    let shortcutPrompt: String
    let shortcutRemove: String
    let shortcutCaption: String
    let shortcutReserved: String
    let shortcutNeedsModifier: String
    let shortcutConflict: String
